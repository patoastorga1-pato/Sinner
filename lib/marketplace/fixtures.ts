function photoUrl(id: string) {
  const index = Array.from(id).reduce((sum, character) => sum + character.charCodeAt(0), 0) % developmentPhotoUrls.length;
  return developmentPhotoUrls[index];
}

function buildFixture(input: FixtureInput): SpaceDetailData {
  const photos = input.photoIds.map((id, index) => ({
    id: `${input.id}-photo-${index + 1}`,
    url: photoUrl(id),
    sortOrder: index,
    isCover: index === 0,
    altText: `${input.name} view ${index + 1}`,
  }));
  const allowedUses: SpaceAllowedUse[] = Object.entries(allowedUseNames).map(([slug, name]) => ({
    name,
    slug,
    allowed: input.allowedUseSlugs.includes(slug),
    details: null,
  }));
  const reviews: PublicReview[] = input.reviewSeeds.map((review, index) => ({
    id: `${input.id}-review-${index + 1}`,
    rating: review.rating,
    comment: review.comment,
    authorName: review.authorName,
    authorAvatar: null,
    createdAt: new Date(Date.UTC(2026, 7 - index, 18 - index)).toISOString(),
  }));
  const ratingAverage = reviews.length
    ? reviews.reduce((sum, review) => sum + review.rating, 0) / reviews.length
    : 0;
  const rules: SpaceRule[] = input.ruleOverrides ?? [
    { key: "guests", label: "Maximum guests", detail: `Up to ${input.maxGuests} registered guests` },
    { key: "smoking", label: "Smoking", detail: "Not permitted indoors", allowed: false },
    { key: "noise", label: "Noise", detail: "Keep sound within the private space" },
    { key: "cleaning", label: "Cleaning", detail: "Standard cleaning is included in the estimate" },
  ];

  return {
    ...input,
    coverPhoto: photos[0]?.url ?? "/images/hero-sinner-night.png",
    photos,
    amenities: input.amenitySlugs.map((slug) => amenities[slug]).filter((item): item is SpaceAmenity => Boolean(item)),
    allowedUses,
    rules,
    host: hosts[input.hostKey],
    reviews,
    ratingAverage,
    reviewCount: reviews.length,
  };
}

