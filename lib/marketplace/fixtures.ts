type FixtureInput = Omit<
  SpaceDetailData,
  "coverPhoto" | "photos" | "amenities" | "allowedUses" | "rules" | "host" | "reviews" | "ratingAverage" | "reviewCount"
> & {
  photoIds: string[];
  amenitySlugs: string[];
  allowedUseSlugs: string[];
  ruleOverrides?: SpaceRule[];
  hostKey: keyof typeof hosts;
  reviewSeeds: Array<{ rating: number; comment: string; authorName: string }>;
};

